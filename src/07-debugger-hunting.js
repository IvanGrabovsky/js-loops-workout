/**
 * Завдання 7.1: Виправлення помилки Off-by-one у лічильнику
 * У коді була помилка: цикл for (let i = 1; i < n; i++) не враховував останній елемент n включно. Виправити, щоб сумувалися числа від 1 до n включно.
 * - Для n = 3 сума має бути 1 + 2 + 3 = 6.
 * - Якщо n <= 0, повернути 0.
 */
export function fixOffByOneSum(n) {
  // TODO: напишіть вашу реалізацію тут
  let sum = 0;
    for (let i = 1; i < n; i++) {
      sum += i;
    }
    return sum;
}

